#!/usr/bin/env python3
"""PR description lint (policy as code). Fails when the body of a pull request is
not in the standard: sections missing/empty, wrong language for the repo's
visibility, or no technical <details> block.

  pr_lint.py --body-file F --visibility private|public [--title T]
  pr_lint.py --event $GITHUB_EVENT_PATH            (CI: reads body and repo.private)

Private repository -> Portuguese; public -> English. Sections 4-6 (checks, health,
glossary) are generated by CI in a sticky comment, so they are not required here.
Exit 0 ok, 1 fails (messages in the language of the repo).
"""
import argparse, json, re, sys

SEC = {
    "private": {"lang": "pt", "required": ["O que este PR faz", "Por quê", "Risco e como desfazer"],
                "details": "Detalhes técnicos"},
    "public": {"lang": "en", "required": ["What this PR does", "Why", "Risk and how to undo"],
               "details": "Technical details"},
}
PT_WORDS = set("o a os as de do da dos das que não para com uma um por em é são está foi vai ao pelo pela mais mas como se isso este esta sem sobre quando também ainda".split())
EN_WORDS = set("the a an of to and is are was were this that for with not be on in it as by from will has have but or if when also still without about".split())
EXEMPT = {"dependabot[bot]", "luanharaujo-canary[bot]"}  # their bodies are fixed, in English
PLACEHOLDER = re.compile(r"^\s*(<[^>]*>|\.\.\.|todo|tbd|n/?a|-)\s*$", re.I)


def sections(body):
    """{heading: text} for '## ' headings; HTML comments removed first."""
    body = re.sub(r"<!--.*?-->", "", body, flags=re.S)
    out, cur = {}, None
    for ln in body.splitlines():
        m = re.match(r"^##\s+(.+?)\s*$", ln)
        if m:
            cur = m.group(1); out[cur] = ""; continue
        if cur is not None:
            out[cur] += ln + "\n"
    return out


def guess_lang(text):
    text = re.sub(r"`[^`]*`|https?://\S+|<[^>]+>", " ", text)
    w = re.findall(r"[a-záéíóúâêôãõç]+", text.lower())
    pt, en = sum(x in PT_WORDS for x in w), sum(x in EN_WORDS for x in w)
    if pt + en < 4:
        return None  # too short to tell
    return "pt" if pt > en else "en"


def lint(body, visibility):
    cfg = SEC["private" if visibility == "private" else "public"]
    pt = cfg["lang"] == "pt"
    errs = []
    secs = sections(body or "")
    txt_all = ""
    for name in cfg["required"]:
        if name not in secs:
            errs.append((f"Falta a seção \"## {name}\"." if pt else f"Missing section \"## {name}\"."))
            continue
        t = secs[name].strip()
        txt_all += " " + t
        if not t or all(PLACEHOLDER.match(l) for l in t.splitlines() if l.strip()) or len(t) < 15:
            errs.append((f"A seção \"{name}\" está vazia ou é só o modelo." if pt else f"Section \"{name}\" is empty or still the template."))
    if not re.search(r"<details>\s*<summary>\s*" + re.escape(cfg["details"]) + r"\s*</summary>", body or "", re.I):
        errs.append((f"Falta o bloco <details><summary>{cfg['details']}</summary>." if pt else f"Missing the <details><summary>{cfg['details']}</summary> block."))
    g = guess_lang(txt_all)
    if g and g != cfg["lang"]:
        errs.append(("Idioma errado: repositório privado = português simples." if pt else
                     "Wrong language: public repository = English."))
    return errs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--body-file"); ap.add_argument("--visibility", choices=["private", "public"])
    ap.add_argument("--event")
    a = ap.parse_args()
    if a.event:
        ev = json.load(open(a.event))
        pr = ev.get("pull_request") or {}
        user = (pr.get("user") or {}).get("login", "")
        if user in EXEMPT:
            print(f"{user}: body is not ours (Dependabot / canary App): skipped."); return 0
        body = pr.get("body") or ""
        vis = "private" if (ev.get("repository") or {}).get("private") else "public"
    else:
        body = open(a.body_file).read(); vis = a.visibility
    errs = lint(body, vis)
    for e in errs:
        print("::error::" + e)
    if errs:
        print(("Modelo: .github/pull_request_template.md. Corrija a descrição do PR." if vis == "private"
               else "Template: .github/pull_request_template.md. Fix the PR description."))
        return 1
    print("ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
